    val all: List<String> = categories.flatMap { it.emoji }.distinct()

    /** Semua emoji untuk satu tab: 0 = sering dipakai, 1..n = kategori. */
    fun emojisForTab(tab: Int, recent: List<String>): List<String> {
        if (tab <= 0) {
            val base = recent.filter { it.isNotBlank() }.distinct()
            return (base + categories.first().emoji).distinct()
        }
        return categories.getOrNull(tab)?.emoji?.distinct() ?: emptyList()
    }

    /** Jumlah tombol per baris pada panel emoji. */
    private const val COLUMNS = 8

    fun layout(tab: Int, recent: List<String>): KeyboardLayout {
        val rows = mutableListOf<KeyRow>()

        val tabs = mutableListOf<KeySpec>()
        for (i in categories.indices) {
            tabs += KeySpec(
                value = KeyValue.ActionValue(KeyboardAction.EMOJI_TAB, i.toString()),
                label = categories[i].tab,
                style = if (i == tab) KeyStyle.MODIFIER else KeyStyle.FUNCTION,
                width = 1f,
            )
        }
        rows += KeyRow(tabs, height = 0.8f)

        val emoji = emojisForTab(tab, recent)
        val chunks = emoji.chunked(COLUMNS).take(4)
        for (chunk in chunks) {
            val keys = chunk.map {
                KeySpec(value = KeyValue.TextValue(it), label = it, width = 1.25f, style = KeyStyle.NORMAL)
            }.toMutableList()
            while (keys.size < COLUMNS) {
                keys += KeySpec(value = KeyValue.TextValue(""), label = "", width = 1.25f)
            }
            rows += KeyRow(keys, height = 1f)
        }
        while (rows.size < 5) {
            rows += KeyRow(
                List(COLUMNS) { KeySpec(value = KeyValue.TextValue(""), label = "", width = 1.25f) },
                height = 1f,
            )
        }

        rows += KeyRow(
            listOf(
                KeySpec(
                    value = KeyValue.ActionValue(KeyboardAction.SWITCH_LAYER, Layer.LETTERS.id),
                    label = "ABC",
                    width = 1.5f,
                    style = KeyStyle.FUNCTION,
                ),
                KeySpec(
                    value = KeyValue.ActionValue(KeyboardAction.SPACE),
                    label = "spasi",
                    width = 4.0f,
                    style = KeyStyle.SPACE,
                ),
                KeySpec(
                    value = KeyValue.ActionValue(KeyboardAction.BACKSPACE),
                    label = "⌫",
                    width = 1.5f,
                    style = KeyStyle.FUNCTION,
                    repeat = true,
                ),
                KeySpec(
                    value = KeyValue.ActionValue(KeyboardAction.SWITCH_LAYER, Layer.SYMBOLS.id),
                    label = "?123",
                    width = 1.0f,
                    style = KeyStyle.FUNCTION,
                ),
                KeySpec(
                    value = KeyValue.ActionValue(KeyboardAction.SWITCH_LAYER, Layer.SCIENTIFIC.id),
                    label = "ƒx",
                    width = 1.0f,
                    style = KeyStyle.FUNCTION,
                ),
                KeySpec(
                    value = KeyValue.ActionValue(KeyboardAction.ENTER),
                    label = "⏎",
                    width = 1.0f,
                    style = KeyStyle.ACTION,
                ),
            ),
        )

        return KeyboardLayout(layer = Layer.EMOJI, rows = rows, columns = 10f)
    }
